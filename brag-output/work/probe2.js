const puppeteer = require("puppeteer-core");
const EDGE = "C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe";
const W=ms=>new Promise(r=>setTimeout(r,ms));
(async () => {
  const b = await puppeteer.launch({ executablePath: EDGE, headless: "new", args: ["--use-angle=d3d11","--enable-gpu","--ignore-gpu-blocklist"] });
  const p = await b.newPage();
  p.on("pageerror", e => console.log("pageerror:", e.message));
  await p.setViewport({ width: 1920, height: 1080 });
  await p.emulateMediaFeatures([{name:"prefers-color-scheme",value:"dark"}]);
  await p.goto("http://localhost:8765/app.html", { waitUntil: "load" });
  await p.waitForFunction(() => window.__v && !document.querySelector("#loading"), { timeout: 60000 });
  await W(800);
  const ix=n=>`__v.EX.findIndex(e=>e.n===${JSON.stringify(n)})`;
  await p.evaluate(`__v.openTab("ex"); __v.selectEx(${ix("Back squat")}); __v.startCmp(); __v.selectEx(${ix("Romanian deadlift")});`);
  await W(1500); await p.screenshot({ path: "probe-3.png" });
  await p.evaluate(`__v.clearEx(); __v.setWin("2026-10-15",true);
    const A=(n,d,s)=>__v.addToPlan(${"__v.EX.findIndex(e=>e.n===n)"},[],d,s);
    A("Barbell bench press",0,4);A("Overhead press",0,3);A("Triceps pushdown",0,3);
    A("Back squat",2,4);A("Leg press",2,3);A("Leg extension",2,3);
    A("Pull-up",4,4);A("Barbell row",4,3);A("Barbell curl",4,3);
    A("Incline dumbbell press",5,3);A("Lateral raise",5,3);
    __v.openTab("wk"); __v.volOn=true; __v.setMode("vol");`);
  await W(1500); await p.screenshot({ path: "probe-4.png" });
  await p.evaluate(`__v.openOv(); __v.setOvView("mus");`);
  await W(1000); await p.screenshot({ path: "probe-5.png" });
  await p.evaluate(`__v.setOvView("sch");`);
  await W(1000); await p.screenshot({ path: "probe-6.png" });
  await b.close();
})();
